#!/usr/bin/env python3
"""Package the native reader, design values and offline libraries for WKWebView."""

import argparse
import ast
import hashlib
import json
import re
import shutil
import subprocess
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "JustMarkdown/WebSource"
DEST = ROOT / "JustMarkdown/Resources/Web"
VENDOR = ROOT / "vendor"


def replace_once(text, marker, replacement):
    if text.count(marker) != 1:
        raise ValueError(f"Expected one native reader marker: {marker}")
    return text.replace(marker, replacement)


def reader_design(spec):
    names = {
        "hitTarget": "size.hitTarget",
        "floatingIcon": "size.floatingIcon",
        "compactFloatingIcon": "size.compactFloatingIcon",
        "agentWidth": "size.agentWidth",
        "floatingGap": "space.floatingGap",
        "outlineIcon": "size.outlineIcon",
        "homeMark": "size.homeMark",
        "homeEntranceOffset": "space.homeEntranceOffset",
        "homeBrandGap": "space.homeBrandGap",
        "homeGroupGap": "space.homeGroupGap",
        "homeActionGap": "space.homeActionGap",
        "recentsWidth": "size.recentsWidth",
        "recentsMaxHeight": "size.recentsMaxHeight",
    }
    declarations = [
        f"    static let {name}: CGFloat = {float(spec['tokens'][key]['value'].removesuffix('px')):g}"
        for name, key in names.items()
    ]
    declarations += [
        f"    static let {name}Duration: TimeInterval = {spec['motion'][key]['duration'] / 1000:g}"
        for name, key in [
            ("tools", "tools"),
            ("agent", "agentPanel"),
            ("content", "content"),
            ("home", "homeEntrance"),
        ]
    ]
    declarations.append(
        f"    static let homeStagger: TimeInterval = {spec['motion']['homeEntrance']['stagger'] / 1000:g}"
    )
    return (
        "// Generated by build_native_web.py from design/tokens.json.\nimport UIKit\n\n"
        "enum ReaderDesign {\n" + "\n".join(declarations) + "\n}\n"
    )


def vendor_assets():
    assets = json.loads((VENDOR / "assets.json").read_text())
    recorded = set()
    for asset in assets:
        checksums = {
            asset["file"]: asset["sha256"],
            asset["licenseFile"]: asset["licenseSha256"],
            **asset.get("resources", {}),
        }
        for name, expected in checksums.items():
            actual = hashlib.sha256((VENDOR / name).read_bytes()).hexdigest()
            if actual != expected:
                raise ValueError(f"Vendor checksum mismatch: {name}")
            recorded.add(name)
    files = {str(path.relative_to(VENDOR)) for path in VENDOR.rglob("*") if path.is_file()}
    if files - recorded - {"assets.json", "README.md", ".DS_Store"}:
        raise ValueError("Unlisted vendor files; update assets.json before packaging")
    return assets


def web_localizations():
    catalog = json.loads((ROOT / "JustMarkdown/Localizable.xcstrings").read_text())
    used = set()
    for source in SOURCE.rglob("*"):
        if source.suffix == ".js":
            literals = re.findall(
                r"""\bt\(\s*((?:"(?:\\.|[^"\\])*"|'(?:\\.|[^'\\])*'))""", source.read_text()
            )
            used.update(ast.literal_eval(literal) for literal in literals)
        elif source.suffix == ".html":
            used.update(re.findall(r'data-l10n(?:-aria-label)?="([^"]+)"', source.read_text()))
    missing = used - catalog["strings"].keys()
    if missing:
        raise ValueError(
            "Web UI strings missing from the String Catalog: " + ", ".join(sorted(missing))
        )
    languages = {catalog["sourceLanguage"]}
    for entry in catalog["strings"].values():
        if entry.get("shouldTranslate", True):
            languages.update(entry.get("localizations", {}))
    translations = {language: {} for language in sorted(languages)}
    for key, entry in catalog["strings"].items():
        if not entry.get("shouldTranslate", True):
            continue
        placeholders = set(re.findall(r"\{([a-zA-Z]\w*)\}", key))
        for language, strings in translations.items():
            unit = entry.get("localizations", {}).get(language, {}).get("stringUnit", {})
            value = unit.get("value", key if language == catalog["sourceLanguage"] else None)
            if value is None:
                raise ValueError(f"Missing {language} translation: {key}")
            if set(re.findall(r"\{([a-zA-Z]\w*)\}", value)) != placeholders:
                raise ValueError(f"Mismatched {language} placeholders: {key}")
            strings[key] = value
    return translations


def generate(destination):
    spec = json.loads((ROOT / "design/tokens.json").read_text())
    assets = vendor_assets()
    declarations = [f"  {token['css']}: {token['value']};" for token in spec["tokens"].values()]
    for name, motion in spec["motion"].items():
        declarations += [
            f"  --mdv-duration-{name}: {motion['duration']}ms;",
            f"  --mdv-ease-{name}: {motion['easing']};",
        ]
    styles = "#mdv-reading-concept .mdv-app {\n" + "\n".join(declarations) + "\n}"
    bindings = {
        "design-tokens": '<style id="mdv-design-tokens">\n' + styles + "\n</style>",
        "motion-spec": '<script id="mdv-motion-spec" type="application/json">\n'
        + json.dumps(spec["motion"], indent=2)
        + "\n</script>",
        "vendor-scripts": "\n".join(f'<script src="{asset["file"]}"></script>' for asset in assets),
        "reader-styles": "<style>\n" + (SOURCE / "reader.css").read_text() + "\n</style>",
        "native-styles": "<style>\n" + (SOURCE / "native.css").read_text() + "\n</style>",
        "agent-styles": '<style id="mdv-agent-styles">\n'
        + (SOURCE / "agent/agent.css").read_text()
        + "\n</style>",
        "agent-markup": (SOURCE / "agent/panel.html").read_text(),
    }
    html = (SOURCE / "reader.html").read_text()
    for marker, value in bindings.items():
        html = replace_once(html, f"<!-- {marker} -->", value)
    runtime = (SOURCE / "reader.js").read_text()
    for module in ["native-bridge", "native-agent"]:
        runtime = replace_once(
            runtime, f"    /* {module} */", (SOURCE / f"{module}.js").read_text()
        )

    package = destination / "Web"
    package.mkdir()
    (package / "index.html").write_text(html)
    (package / "reader.js").write_text(runtime)
    localization = replace_once(
        (SOURCE / "localization.js").read_text(),
        "/* localization-data */ {}",
        json.dumps(web_localizations(), ensure_ascii=False, separators=(",", ":")),
    )
    (package / "localization.js").write_text(localization)
    shutil.copy2(SOURCE / "agent/agent.js", package / "agent.js")
    shutil.copy2(SOURCE / "source-history.js", package / "source-history.js")
    for asset in assets:
        for key in ["file", "licenseFile"]:
            shutil.copy2(VENDOR / asset[key], package / asset[key])
    shutil.copytree(VENDOR / "katex-fonts", package / "fonts")
    shutil.copy2(VENDOR / "katex.css", package / "katex.css")
    (destination / "ReaderDesign.swift").write_text(reader_design(spec))
    shutil.copytree(ROOT / "JustMarkdownTests/Fixtures/ReadingGuide", destination / "Sample")


def fingerprints(directory):
    return {
        path.relative_to(directory): hashlib.sha256(path.read_bytes()).hexdigest()
        for path in directory.rglob("*")
        if path.is_file()
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Check generated files without changing them",
    )
    args = parser.parse_args()
    subprocess.run(
        [
            "xcrun",
            "--sdk",
            "macosx",
            "swift",
            str(ROOT / "scripts/build_brand_assets.swift"),
            *(["--check"] if args.check else []),
        ],
        check=True,
    )
    with tempfile.TemporaryDirectory(prefix="justmarkdown-web-") as temporary:
        generated = Path(temporary)
        generate(generated)
        destinations = {
            "Web": DEST,
            "Sample": DEST.parent / "Sample",
            "ReaderDesign.swift": ROOT / "JustMarkdown/ReaderDesign.swift",
        }
        if args.check:
            stale = []
            for name, target in destinations.items():
                source = generated / name
                matches = target.exists() and (
                    fingerprints(source) == fingerprints(target)
                    if source.is_dir()
                    else source.read_bytes() == target.read_bytes()
                )
                if not matches:
                    stale.append(str(target.relative_to(ROOT)))
            if stale:
                raise SystemExit(
                    "Stale generated files: "
                    + ", ".join(stale)
                    + ". Run python3 scripts/build_native_web.py."
                )
            print("Offline dependency checksums and generated resources match.")
            return
        # Replace complete trees so removed resources cannot survive in the bundle.
        DEST.parent.mkdir(parents=True, exist_ok=True)
        for name, target in destinations.items():
            if target.is_dir():
                shutil.rmtree(target)
            elif target.exists():
                target.unlink()
            shutil.move(generated / name, target)
    print("Packaged native reader, verified offline libraries, fonts and reading fixture.")


if __name__ == "__main__":
    main()
